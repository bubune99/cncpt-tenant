// Writes lib/far-cms/owned-models.ts from prisma/far-cms/schema.prisma with @far-cms/db's own schema readers, so the
// lists the site scope uses are read the same way the rule reads them. Run after the far-cms schema changes:
//   node scripts/far-cms/gen-owned-models.mjs            (writes)
//   node scripts/far-cms/gen-owned-models.mjs --check    (exits 1 if the file is out of date)
import { readFileSync, writeFileSync } from "node:fs"
import { siteOwnedModels, siteUniqueKeys, siteRelations } from "@far-cms/db"

const schema = readFileSync("prisma/far-cms/schema.prisma", "utf8")
const owned = [...siteOwnedModels(schema)].sort()
const uniques = Object.fromEntries([...siteUniqueKeys(schema)].sort(([a], [b]) => a.localeCompare(b)))
const relations = Object.fromEntries([...siteRelations(schema)].sort(([a], [b]) => a.localeCompare(b)).map(([m, f]) => [m, Object.fromEntries([...f].sort())]))
const out = `// GENERATED by scripts/far-cms/gen-owned-models.mjs from prisma/far-cms/schema.prisma. Do not edit by hand.
// Site-owned models, per-site unique keys and relation fields, read with @far-cms/db's own schema readers.
import type { SiteRelations, SiteUniques } from "@far-cms/db"

export const OWNED_MODELS: ReadonlySet<string> = new Set(${JSON.stringify(owned)})

export const SITE_UNIQUES: SiteUniques = new Map(Object.entries(${JSON.stringify(uniques)}))

export const SITE_RELATIONS: SiteRelations = new Map(Object.entries(${JSON.stringify(relations)}).map(([m, f]) => [m, new Map(Object.entries(f as Record<string, string>))]))
`
const path = "lib/far-cms/owned-models.ts"
if (process.argv.includes("--check")) {
  if (readFileSync(path, "utf8") !== out) { console.error(`${path} is out of date: run node scripts/far-cms/gen-owned-models.mjs`); process.exit(1) }
  console.log(`${path} is up to date`)
} else {
  writeFileSync(path, out)
  console.log(`${owned.length} site-owned models, ${Object.values(uniques).flat().length} per-site unique keys, ${Object.keys(relations).length} models with relations`)
}
